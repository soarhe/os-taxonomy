groups=[]
types={'C':'CONCEPTUAL','P':'PROCEDURAL','R':'REPRESENTATIONAL','L':'LANGUAGE','M':'META'}
def group(source, code, domain, grades, pages, section, summary, rows, source_grades=None):
    items=[]
    for line in rows.strip().splitlines():
        fields=line.split('|'); assert len(fields)==6,line
        ident,typ,name,description,evidence,prereqs=fields
        ev=evidence.split('；')
        deps=[]
        for d in filter(None,prereqs.split(';')):
            p,why=d.split('~'); soft=p.startswith('?'); p=p.lstrip('?')
            deps.append([p,'soft' if soft else 'hard',why])
        items.append({'id':ident,'type':types[typ],'name':name,'description':description,'evidence':ev,
            'assessment':'请让{{name}}在未练过的同类情境中完成以下任务，并用讲述、作品或操作说明依据：'+evidence+'。记录独立完成与获得帮助的区别，不仅凭答案判断掌握。','prerequisites':deps})
    groups.append({'source':source,'code':code,'domain':domain,'grades':grades,'pages':list(range(pages[0],pages[-1]+1)),
        'sourceGrades':source_grades or grades,'section':section,'summary':summary,'items':items})

